const defaultLang = localStorage.getItem('mnm-lang') || 'kn';
const langToggle = document.querySelector('[data-lang-toggle]');

function applyLanguage(lang) {
  const labels = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  document.body.classList.toggle('lang-kn', lang === 'kn');

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (labels[key]) {
      element.textContent = labels[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (labels[key]) {
      element.setAttribute('placeholder', labels[key]);
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach((element) => {
    const key = element.dataset.i18nTitle;
    if (labels[key]) {
      element.setAttribute('title', labels[key]);
    }
  });

  document.querySelectorAll('[data-whatsapp-en][data-whatsapp-kn]').forEach((link) => {
    link.href = lang === 'kn' ? link.dataset.whatsappKn : link.dataset.whatsappEn;
  });

  const pageTitleKey = document.querySelector('title')?.dataset.i18nTitle;
  if (pageTitleKey && labels[pageTitleKey]) {
    document.title = labels[pageTitleKey];
  }

  if (langToggle) {
    langToggle.textContent = lang === 'en' ? 'ಕನ್ನಡ' : 'EN';
  }

  localStorage.setItem('mnm-lang', lang);
}

if (langToggle) {
  langToggle.addEventListener('click', () => {
    const nextLang = document.documentElement.lang === 'kn' ? 'en' : 'kn';
    applyLanguage(nextLang);
  });
}

applyLanguage(defaultLang);

